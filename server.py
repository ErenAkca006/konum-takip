@app.post("/api/location")
def receive_location():
    payload = request.get_json(silent=True) or {}
    lat = payload.get("lat")
    lon = payload.get("lon")
    accuracy = payload.get("accuracy")
    timestamp = payload.get("timestamp") or datetime.utcnow().isoformat()

    if lat is None or lon is None:
        return jsonify({"error": "lat and lon are required"}), 400

    conn = get_db_connection()
    query = "INSERT INTO locations (lat, lon, accuracy, timestamp) VALUES (%s, %s, %s, %s)" if os.getenv("DATABASE_URL") else "INSERT INTO locations (lat, lon, accuracy, timestamp) VALUES (?, ?, ?, ?)"
    conn.execute(
        query,
        (float(lat), float(lon), float(accuracy) if accuracy is not None else None, timestamp),
    )
    conn.commit()
    if os.getenv("DATABASE_URL"):
        location_id = conn.execute("SELECT id FROM locations ORDER BY id DESC LIMIT 1").fetchone()["id"]
    else:
        location_id = conn.execute("SELECT last_insert_rowid() AS id").fetchone()["id"]
    conn.close()

    email_result = send_email(float(lat), float(lon), float(accuracy) if accuracy is not None else 0, timestamp)
    return jsonify({
        "status": "ok",
        "id": location_id,
        "email": email_result,
        "timestamp": timestamp,
    })


