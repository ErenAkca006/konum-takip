@app.get("/api/history")
def history():
    conn = get_db_connection()
    query = "SELECT lat, lon, accuracy, timestamp FROM locations ORDER BY id DESC LIMIT 20"
    rows = conn.execute(query).fetchall()
    conn.close()
    return jsonify([
        {
            "lat": row["lat"],
            "lon": row["lon"],
            "accuracy": row["accuracy"],
            "timestamp": row["timestamp"],
        }
        for row in rows
    ])


