def init_db():
    if os.getenv("DATABASE_URL"):
        with psycopg.connect(os.environ["DATABASE_URL"]) as conn:
            with conn.cursor() as cursor:
                cursor.execute(
                    """
                    CREATE TABLE IF NOT EXISTS public.locations (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        lat DOUBLE PRECISION NOT NULL,
                        lon DOUBLE PRECISION NOT NULL,
                        accuracy DOUBLE PRECISION,
                        timestamp TIMESTAMPTZ NOT NULL,
                        created_at TIMESTAMPTZ DEFAULT NOW()
                    )
                    """
                )
        return

    with sqlite3.connect(DB_PATH) as conn:
        conn.execute(
            """
            CREATE TABLE IF NOT EXISTS locations (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                lat REAL NOT NULL,
                lon REAL NOT NULL,
                accuracy REAL,
                timestamp TEXT NOT NULL,
                created_at TEXT DEFAULT CURRENT_TIMESTAMP
            )
            """
        )


init_db()


def get_db_connection():
    if os.getenv("DATABASE_URL"):
        return psycopg.connect(os.environ["DATABASE_URL"], row_factory=dict_row)

    conn = sqlite3.connect(DB_PATH)
    conn.row_factory = sqlite3.Row
    return conn


def admin_required(view):
    @wraps(view)
    def wrapped_view(*args, **kwargs):
        username = os.getenv("ADMIN_USERNAME", "").strip()
        password = os.getenv("ADMIN_PASSWORD", "")
        credentials = request.authorization
        if not username or not password:
            return jsonify({"error": "Admin credentials are not configured"}), 503
        if not credentials or credentials.username != username or credentials.password != password:
            response = jsonify({"error": "Authentication required"})
            response.status_code = 401
            response.headers["WWW-Authenticate"] = 'Basic realm="Location Admin"'
            return response
        return view(*args, **kwargs)

    return wrapped_view


def send_email(lat, lon, accuracy, timestamp):
    smtp_host = os.getenv("SMTP_HOST", "smtp.gmail.com")
    smtp_port = int(os.getenv("SMTP_PORT", "587"))
    smtp_user = (os.getenv("SMTP_USER", "") or "").strip()
    smtp_password = (os.getenv("SMTP_PASSWORD", "") or "").strip()
    to_email = (os.getenv("TO_EMAIL", "erenakc69@gmail.com") or "erenakc69@gmail.com").strip()

    placeholder = "PASTE_YOUR_GMAIL_APP_PASSWORD_HERE"
    if not smtp_user or not smtp_password or smtp_password == placeholder or "PASTE_" in smtp_password.upper():
        return {
            "status": "skipped",
            "message": "SMTP credentials are not set. Replace the placeholder in .env with a real Gmail app password to enable automatic email delivery.",
        }

    map_url = f"https://www.google.com/maps?q={lat},{lon}"
    subject = "Kişisel konum takibi"
    body = (
        f"Tarih: {timestamp}\n"
        f"Koordinatlar: {lat:.6f}, {lon:.6f}\n"
        f"Doğruluk: ±{accuracy} m\n"
        f"Harita: {map_url}"
    )

    msg = EmailMessage()
    msg["Subject"] = subject
    msg["From"] = smtp_user
    msg["To"] = to_email
    msg.set_content(body)

    with smtplib.SMTP(smtp_host, smtp_port) as server:
        server.starttls()
        server.login(smtp_user, smtp_password)
        server.send_message(msg)

    return {"status": "sent"}


